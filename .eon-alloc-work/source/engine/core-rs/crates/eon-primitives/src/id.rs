#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ids_carry_prefix_and_full_body() {
        let id = ObjectiveId::new();
        assert!(id.as_str().starts_with("obj_"));
        assert_eq!(id.as_str().len(), 4 + ULID_LEN);
    }

    #[test]
    fn same_thread_ids_are_strictly_increasing() {
        let mut previous = generate_ulid_u128();
        for _ in 0..50_000 {
            let next = generate_ulid_u128();
            assert!(next > previous, "ULIDs must be strictly monotonic");
            previous = next;
        }
    }

    #[test]
    fn entropy_is_seeded_from_os_randomness() {
        // The old implementation left the upper entropy bits zero; CSPRNG seeding sets them.
        let high_bits_set = (0..64).any(|_| (generate_ulid_u128() & MASK_80) >> 64 != 0);
        assert!(high_bits_set);
    }

    #[test]
    fn wrong_prefix_is_rejected_with_expected_prefix() {
        let err = ObjectiveId::from_raw(format!("task_{}", generate_ulid_string())).unwrap_err();
        match err {
            EonError::InvalidId {
                expected_prefix, ..
            } => assert_eq!(expected_prefix, "obj"),
            other => panic!("expected InvalidId, got {other:?}"),
        }
    }

    #[test]
    fn malformed_bodies_are_rejected() {
        let good = generate_ulid_string();
        let too_short = format!("obj_{}", &good[..25]);
        let bad_char = format!("obj_U{}", &good[1..]); // 'U' is excluded from Crockford
        let overflow = format!("obj_Z{}", &good[1..]); // top char above 7 overflows 128 bits
        for raw in [too_short, bad_char, overflow] {
            assert!(
                ObjectiveId::from_raw(raw.clone()).is_err(),
                "accepted {raw}"
            );
        }
    }

    #[test]
    fn generated_id_round_trips_through_from_str() {
        let id = ClaimId::new();
        let parsed: ClaimId = id.to_string().parse().expect("own output must parse");
        assert_eq!(parsed, id);
    }
}
