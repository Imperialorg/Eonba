use std::fmt;
use std::str::FromStr;
use std::sync::Mutex;
use std::time::{SystemTime, UNIX_EPOCH};

use crate::error::EonError;

const CROCKFORD: &[u8; 32] = b"0123456789ABCDEFGHJKMNPQRSTVWXYZ";

/// Maps an ASCII byte to its Crockford value (0..=31), or 0xFF when the byte is not in the alphabet.
const DECODING: [u8; 256] = {
    let mut table = [0xFFu8; 256];
    let mut i = 0;
    while i < 32 {
        table[CROCKFORD[i] as usize] = i as u8;
        i += 1;
    }
    table
};

const ULID_LEN: usize = 26;
const MASK_80: u128 = (1u128 << 80) - 1;
const MASK_48: u64 = (1u64 << 48) - 1;

struct UlidState {
    last_ms: u64,
    last_rand_80: u128,
}

static ULID_STATE: Mutex<UlidState> = Mutex::new(UlidState {
    last_ms: 0,
    last_rand_80: 0,
});

/// Returns a 128-bit ULID: 48-bit millisecond timestamp followed by 80 bits of entropy.
///
/// Entropy is drawn from the OS CSPRNG at each new millisecond. Within the same
/// millisecond (or after a backward clock step) the entropy is incremented, so
/// IDs generated by one process are strictly increasing.
pub fn generate_ulid_u128() -> u128 {
    let now_ms = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as u64
        & MASK_48;

    let mut state = ULID_STATE
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner());
    if now_ms > state.last_ms {
        let mut buf = [0u8; 10];
        getrandom::fill(&mut buf).expect("OS CSPRNG unavailable");
        let rand_80 = buf.iter().fold(0u128, |acc, &b| (acc << 8) | b as u128);
        state.last_ms = now_ms;
        state.last_rand_80 = rand_80 & MASK_80;
    } else {
        state.last_rand_80 = state.last_rand_80.wrapping_add(1) & MASK_80;
        if state.last_rand_80 == 0 {
            // An 80-bit overflow inside one millisecond is unreachable in practice; advance the logical clock.
            state.last_ms += 1;
        }
    }

    ((state.last_ms as u128) << 80) | state.last_rand_80
}

/// Encodes a 128-bit value as 26 Crockford Base32 characters.
pub fn encode_ulid(mut value: u128) -> String {
    let mut out = [b'0'; ULID_LEN];
    for slot in out.iter_mut().rev() {
        *slot = CROCKFORD[(value & 0x1F) as usize];
        value >>= 5;
    }
    String::from_utf8(out.to_vec()).expect("Crockford alphabet is ASCII")
}

/// Returns true when `suffix` is a canonical 26-character ULID body that fits in 128 bits.
pub fn validate_ulid_suffix(suffix: &str) -> bool {
    let bytes = suffix.as_bytes();
    if bytes.len() != ULID_LEN {
        return false;
    }
    // The first character carries only the top 3 bits of a 128-bit value, so it must be 0..=7.
    if DECODING[bytes[0] as usize] > 7 {
        return false;
    }
    bytes.iter().all(|&b| DECODING[b as usize] != 0xFF)
}

/// Generates a fresh 26-character ULID body.
pub fn generate_ulid_string() -> String {
    encode_ulid(generate_ulid_u128())
}

macro_rules! define_typed_id {
    ($(#[$meta:meta])* $type_name:ident, $prefix:literal) => {
        $(#[$meta])*
        #[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub struct $type_name(String);

        impl $type_name {
            pub const PREFIX: &'static str = $prefix;

            pub fn new() -> Self {
                Self(format!("{}_{}", Self::PREFIX, generate_ulid_string()))
            }

            /// Parses an untrusted string, checking both the type prefix and the ULID body.
            pub fn from_raw(raw: String) -> Result<Self, EonError> {
                let valid = raw
                    .strip_prefix(concat!($prefix, "_"))
                    .is_some_and(validate_ulid_suffix);
                if valid {
                    Ok(Self(raw))
                } else {
                    Err(EonError::InvalidId {
                        expected_prefix: Self::PREFIX,
                        actual: raw,
                    })
                }
            }

            pub fn as_str(&self) -> &str {
                &self.0
            }
        }

        impl Default for $type_name {
            fn default() -> Self {
                Self::new()
            }
        }

        impl fmt::Display for $type_name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(&self.0)
            }
        }

        impl FromStr for $type_name {
            type Err = EonError;

            fn from_str(s: &str) -> Result<Self, Self::Err> {
                Self::from_raw(s.to_string())
            }
        }

        #[cfg(feature = "serde")]
        impl serde::Serialize for $type_name {
            fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                serializer.serialize_str(&self.0)
            }
        }

        #[cfg(feature = "serde")]
        impl<'de> serde::Deserialize<'de> for $type_name {
            fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                let raw = String::deserialize(deserializer)?;
                Self::from_raw(raw).map_err(serde::de::Error::custom)
            }
        }
    };
}

